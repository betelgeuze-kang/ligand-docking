#!/usr/bin/env python3
"""Emit the authoritative benchmark claim ledger as JSON + Markdown (read-only).

The ledger governs how benchmark results may be described. It computes nothing
scientific; it pins each headline number to a claim scope, allowed/disallowed
wording, and a claim boundary.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from betelgeuze_product.benchmark_ledger import CLAIM_SCOPES, current_ledger

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT_JSON = "runs/benchmark_ledger_current.json"
DEFAULT_OUT_MD = "docs/BENCHMARK_LEDGER_CURRENT.md"


def _resolve(path_like: str | Path) -> Path:
    path = Path(path_like)
    return path if path.is_absolute() else ROOT / path


def _render_markdown(ledger: dict[str, Any]) -> str:
    summary = ledger["summary"]
    lines = [
        "# Benchmark Claim Ledger (current)",
        "",
        "Authoritative source of truth for **how Betelgeuze benchmark results may be",
        "described**. Generated by `tools/product/build_benchmark_ledger.py` from",
        "`betelgeuze_product/benchmark_ledger.py`. Edit the module, not this file.",
        "",
        "External messaging may cite ONLY rows with `external_safe=true` and must stay",
        "within each row's claim boundary. Locked / reject / scaffold rows are never",
        "product claims. See `.kiro/steering/claim_safe_wording.md`.",
        "",
        f"- schema_version: `{summary['schema_version']}`",
        f"- entries: `{summary['entry_count']}`",
        f"- external-safe entries: `{summary['external_safe_count']}`",
        f"- locked/reject/scaffold entries: `{summary['locked_or_reject_count']}`",
        "",
        "## Claim scopes",
        "",
        "| scope | meaning |",
        "| --- | --- |",
    ]
    for scope, meaning in CLAIM_SCOPES.items():
        lines.append(f"| `{scope}` | {meaning} |")
    lines.extend(
        [
            "",
            "## Entries",
            "",
            "| entry | scope | external_safe | gate | PR-AUC | CI-low | top20 | claim boundary |",
            "| --- | --- | :--: | --- | --: | --: | --: | --- |",
        ]
    )
    for row in ledger["entries"]:
        def _fmt(value: Any) -> str:
            return "" if value is None else (f"{value:.4f}" if isinstance(value, float) else str(value))

        lines.append(
            "| `{entry_id}` | `{scope}` | {safe} | `{gate}` | {pr} | {ci} | {topk} | {boundary} |".format(
                entry_id=row["entry_id"],
                scope=row["claim_scope"],
                safe="yes" if row["external_safe"] else "no",
                gate=row["gate_status"],
                pr=_fmt(row["pr_auc"]),
                ci=_fmt(row["ci_low"]),
                topk=_fmt(row["topk"]),
                boundary=row["claim_boundary"],
            )
        )
    lines.extend(["", "## Approved external wording (external-safe rows)", ""])
    for row in ledger["entries"]:
        if row["external_safe"]:
            lines.append(f"- **{row['entry_id']}**: {row['allowed_external_wording']}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build the benchmark claim ledger.")
    parser.add_argument("--out-json", default=DEFAULT_OUT_JSON)
    parser.add_argument("--out-md", default=DEFAULT_OUT_MD)
    args = parser.parse_args(argv)

    ledger = current_ledger()
    out_json = _resolve(args.out_json)
    out_md = _resolve(args.out_md)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(json.dumps(ledger, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")
    out_md.write_text(_render_markdown(ledger), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
