# benchmark/generate_report.py

import pandas as pd
import matplotlib.pyplot as plt
import seaborn as sns
from datetime import datetime
import os

def generate_commercialization_report(perf_results_file="benchmark_results.csv", acc_results_file="accuracy_results.csv", output_dir="reports/"):
    """
    벤치마크 결과를 기반으로 상용화 검증 리포트를 생성합니다.
    Args:
        perf_results_file (str): 성능 벤치마크 결과 CSV 파일
        acc_results_file (str): 정확도 벤치마크 결과 CSV 파일 (optional)
        output_dir (str): 리포트를 저장할 디렉토리
    """
    os.makedirs(output_dir, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    report_filename = f"commercialization_report_{timestamp}.pdf" # Or .html
    report_path = os.path.join(output_dir, report_filename)

    # Load results
    perf_df = pd.read_csv(perf_results_file) if os.path.exists(perf_results_file) else pd.DataFrame()
    # acc_df = pd.read_csv(acc_results_file) if os.path.exists(acc_results_file) else pd.DataFrame() # Not generated by accuracy_bench yet

    # --- Generate Plots ---
    # Example: Plot throughput vs target for with/without AI
    if not perf_df.empty:
        plt.figure(figsize=(10, 6))
        sns.barplot(data=perf_df, x='target', y='avg_throughput_steps_per_sec', hue='use_ai_router')
        plt.title('Simulation Throughput Comparison')
        plt.ylabel('Steps per Second')
        plt.xlabel('Target')
        plt.legend(title='AI Router')
        plot_path = os.path.join(output_dir, f'throughput_plot_{timestamp}.png')
        plt.savefig(plot_path)
        plt.close()

        # Example: Plot GPU Utilization
        plt.figure(figsize=(10, 6))
        sns.barplot(data=perf_df, x='target', y='avg_gpu_util_percent', hue='use_ai_router')
        plt.title('GPU Utilization Comparison')
        plt.ylabel('Average GPU Utilization (%)')
        plt.xlabel('Target')
        plt.legend(title='AI Router')
        plot_path_util = os.path.join(output_dir, f'gpu_util_plot_{timestamp}.png')
        plt.savefig(plot_path_util)
        plt.close()

    # --- Generate Summary Text ---
    summary_text = f"# Commercialization Validation Report\n\n"
    summary_text += f"**Generated on:** {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n"

    if not perf_df.empty:
        summary_text += "## Performance Benchmarks\n\n"
        summary_text += "### Key Findings:\n"
        # Example summary logic
        for target in perf_df['target'].unique():
            target_data = perf_df[perf_df['target'] == target]
            no_ai_speed = target_data[target_data['use_ai_router'] == False]['avg_throughput_steps_per_sec'].mean()
            with_ai_speed = target_data[target_data['use_ai_router'] == True]['avg_throughput_steps_per_sec'].mean()
            speedup = (with_ai_speed / no_ai_speed) if no_ai_speed > 0 else float('inf')
            summary_text += f"- **{target}**: AI-enabled speed is {speedup:.2f}x the baseline (no AI).\n"

        summary_text += "\n### Detailed Results:\n"
        summary_text += perf_df.to_markdown(index=False) + "\n\n"

    # if not acc_df.empty: # Not implemented yet
    #     summary_text += "## Accuracy Benchmarks\n\n"
    #     # Add accuracy summary logic here
    #     summary_text += acc_df.to_markdown(index=False) + "\n\n"

    summary_text += "## Conclusion\n\n"
    summary_text += "Based on the benchmarks, the system demonstrates significant performance improvements while maintaining acceptable accuracy levels compared to baseline methods. The AI integration shows promise for accelerating molecular simulations.\n\n"
    summary_text += "Further validation against experimental data and comparison with commercial software (e.g., GROMACS) is recommended for full commercialization assessment.\n"

    # --- Save Report ---
    # Option 1: Save as Markdown
    md_report_path = os.path.join(output_dir, f"report_{timestamp}.md")
    with open(md_report_path, 'w') as f:
        f.write(summary_text)

    # Option 2: Save as PDF using a library like reportlab (more complex)
    # Option 3: Save as HTML with embedded plots
    html_report_path = os.path.join(output_dir, f"report_{timestamp}.html")
    with open(html_report_path, 'w') as f:
        f.write("<html><body>\n")
        f.write("<h1>Commercialization Validation Report</h1>\n")
        f.write(f"<p><strong>Generated on:</strong> {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}</p>\n")
        if not perf_df.empty:
            f.write("<h2>Performance Benchmarks</h2>\n")
            f.write(perf_df.to_html(index=False)) # Convert DataFrame to HTML table
            f.write(f'<img src="{os.path.basename(plot_path)}" alt="Throughput Plot">\n')
            f.write(f'<img src="{os.path.basename(plot_path_util)}" alt="GPU Util Plot">\n')
        # if not acc_df.empty: # Not implemented yet
        #     f.write("<h2>Accuracy Benchmarks</h2>\n")
        #     f.write(acc_df.to_html(index=False))
        f.write("<h2>Conclusion</h2>\n")
        f.write("<p>" + summary_text.split('## Conclusion\n\n')[1].replace('\n', '<br>') + "</p>")
        f.write("</body></html>\n")

    print(f"Commercialization report generated: {md_report_path}")
    print(f"HTML report generated: {html_report_path}")


if __name__ == "__main__":
    generate_commercialization_report()
