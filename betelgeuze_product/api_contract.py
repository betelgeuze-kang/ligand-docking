def _parse_api(root: Path) -> ast.Module | None:
    path = root / "api" / "product.py"
    if not path.is_file():
        return None
    try:
        return ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return None


def _parse_module(path: Path) -> ast.Module | None:
    if not path.is_file():
        return None
    try:
        return ast.parse(path.read_text(encoding="utf-8"))
    except (OSError, SyntaxError):
        return None


def _product_accounting_import_aliases(tree: ast.Module | None) -> dict[str, str]:
    if tree is None:
        return {}
    aliases: dict[str, str] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.ImportFrom):
            continue
        if node.module != "api.product_accounting":
            continue
        for alias in node.names:
            local_name = alias.asname or alias.name
            aliases[local_name] = alias.name
    return aliases


def _status_response_helper_functions(
    root: Path,
    *,
    api_tree: ast.Module | None,
    api_functions: dict[str, ast.FunctionDef | ast.AsyncFunctionDef],
) -> dict[str, ast.FunctionDef | ast.AsyncFunctionDef]:
    accounting_tree = _parse_module(root / "api" / "product_accounting.py")
    accounting_functions = _function_nodes(accounting_tree)
    helpers = dict(api_functions)
    helpers.update(accounting_functions)
    for local_name, original_name in _product_accounting_import_aliases(api_tree).items():
        function = accounting_functions.get(original_name)
        if function is not None:
            helpers[local_name] = function
    return helpers


def _function_nodes(tree: ast.Module | None) -> dict[str, ast.FunctionDef | ast.AsyncFunctionDef]:
    if tree is None:
        return {}
    return {
        node.name: node
        for node in ast.walk(tree)
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))
    }


def _route_for(node: ast.FunctionDef | ast.AsyncFunctionDef) -> tuple[str, str] | None:
    for decorator in node.decorator_list:
        if not isinstance(decorator, ast.Call) or not isinstance(decorator.func, ast.Attribute):
            continue
        if decorator.func.attr not in {"get", "post"}:
            continue
        if decorator.args and isinstance(decorator.args[0], ast.Constant) and isinstance(decorator.args[0].value, str):
            return decorator.func.attr.upper(), decorator.args[0].value
    return None


def _model_fields(tree: ast.Module | None) -> dict[str, set[str]]:
    if tree is None:
        return {}
    fields: dict[str, set[str]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.ClassDef):
            continue
        if not any(getattr(base, "id", "") == "BaseModel" for base in node.bases):
            continue
        names: set[str] = set()
        for stmt in node.body:
            if isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name):
                names.add(stmt.target.id)
        fields[node.name] = names
    return fields


def _literal_return_keys(
    node: ast.FunctionDef | ast.AsyncFunctionDef | None,
    functions: dict[str, ast.FunctionDef | ast.AsyncFunctionDef] | None = None,
    _seen: set[str] | None = None,
) -> set[str]:
    if node is None:
        return set()
    functions = functions or {}
    _seen = _seen or set()
    keys: set[str] = set()
    for child in ast.walk(node):
        if not isinstance(child, ast.Return):
            continue
        value = child.value
        if isinstance(value, ast.Dict):
            for key, item_value in zip(value.keys, value.values):
                if isinstance(key, ast.Constant) and isinstance(key.value, str):
                    keys.add(key.value)
                elif (
                    key is None
                    and isinstance(item_value, ast.Call)
                    and isinstance(item_value.func, ast.Name)
                    and item_value.func.id in functions
                    and item_value.func.id not in _seen
                ):
                    keys.update(
                        _literal_return_keys(
                            functions[item_value.func.id],
                            functions,
                            _seen | {item_value.func.id},
                        )
                    )
    return keys


def build_product_api_contract(*, root: str | Path = ".") -> dict[str, Any]:
    root_path = Path(root).resolve()
    tree = _parse_api(root_path)
    functions = _function_nodes(tree)
    status_response_helpers = _status_response_helper_functions(
        root_path,
        api_tree=tree,
        api_functions=functions,
    )
    routes = {name: _route_for(functions[name]) for name in functions}
    missing_routes = sorted(
        f"{method} {path}" for name, (method, path) in EXPECTED_ROUTES.items() if routes.get(name) != (method, path)
    )

    model_fields = _model_fields(tree)
    missing_model_fields = sorted(
        f"{model}.{field}"
        for model, expected in EXPECTED_MODEL_FIELDS.items()
        for field in expected - model_fields.get(model, set())
    )

    docking_keys = _literal_return_keys(functions.get("submit_docking_job"), functions)
    docking_missing = sorted(REQUIRED_DOCKING_RESPONSE_KEYS - docking_keys)
    status_function_names = [
        name
        for name in EXPECTED_ROUTES
        if name.startswith("get_product_") and name not in {"get_product_api_contract"}
    ]
    status_missing = sorted(
        f"{name}.{key}"
        for name in status_function_names
        for key in REQUIRED_STATUS_RESPONSE_KEYS
        - _literal_return_keys(functions.get(name), status_response_helpers)
    )
    domain_status_missing = sorted(
        f"{name}.{key}"
        for name, required_keys in REQUIRED_STATUS_DOMAIN_KEYS.items()
        for key in required_keys
        - _literal_return_keys(functions.get(name), status_response_helpers)
    )
